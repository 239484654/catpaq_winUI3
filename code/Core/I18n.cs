    private static readonly Dictionary<string, Dictionary<string, string>> Dicts;

    static I18n()
    {
        Dicts = new()
        {
            ["zh"] = Zh,
            ["it"] = It,
            ["ru"] = Ru,
            ["nl"] = Nl,
            ["de"] = De,
            ["fr"] = Fr,
            ["es"] = Es,
            ["pt"] = Pt,
            ["ja"] = Ja,
            ["ko"] = Ko,
        };
    }

    /// <summary>按当前语言取文案；未命中或语言无字典时返回英文默认值。</summary>
    public static string T(string key, string en, string lang)
    {
        if (string.IsNullOrEmpty(lang))
            return en;
        var tag = lang.Split('-')[0].ToLowerInvariant();
        if (Dicts.TryGetValue(tag, out var d) && d.TryGetValue(key, out var s) && s != "")
            return s;
        return en;
    }

