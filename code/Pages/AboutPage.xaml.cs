        var zh = Main.LangName.StartsWith("zh");
        var sb = new System.Text.StringBuilder();
        sb.AppendLine($"Catpaq {version} (WinUI 3)");
        sb.AppendLine();
        sb.AppendLine(Main.T("about.desc", "ZPAQ archive manager built on the zpaqfranz engine."));
        sb.AppendLine();
        sb.Append(Main.T("about.repo", "Repository: "));
        sb.AppendLine("https://github.com/239484654/catpaq_winUI3");
        sb.AppendLine();
        sb.AppendLine(Main.T("about.third", "Third-party acknowledgements:"));
        if (zh)
        {
            sb.AppendLine("• catpaq —— 原始 Lazarus 项目（https://github.com/fcorbelli/catpaq）");
            sb.AppendLine("• Microsoft Windows App SDK / WinUI 3");
            sb.AppendLine("• .NET 10");
            sb.AppendLine("• zpaqfranz（https://zpaqfranz.com）");
