            sb.AppendLine();
            sb.AppendLine(I18n.MitLicense);
        }
        else
        {
            sb.AppendLine("• catpaq — original Lazarus project (https://github.com/fcorbelli/catpaq)");
            sb.AppendLine("• Microsoft Windows App SDK / WinUI 3");
            sb.AppendLine("• .NET 10");
